"""Authored structural specifications for the supported firmware code family.

These generate instructions from semantic operations. No firmware payloads,
bulk byte signatures, disassembly files or downloaded assets are embedded.
"""
from mips16 import Program


def standby(start, values, patched):
    p = Program(start)
    e = p.emit
    e('jal', values['policy'])
    e('cmpi', 2, 1)
    e('li', 4, 13)
    e('bteqz', 'led')
    if patched:
        e('lui', 2, values['preference'] >> 16)
        e('lbu', 2, 2, values['preference'] & 65535)
        e('li', 3, 2)
        e('and', 2, 3)
        e('beqz', 2, 'led')
    e('li', 4, 3)
    p.label('led')
    e('jal', values['led'])
    e('jal', values['cleanup'])
    e('li', 4, 1)
    e('jal', values['auxiliary'])
    e('nop')
    e('lui', 3, values['state_upper'])
    e('addiu', 3, 3, values['state_bias'])
    e('lbu', 2, 3, 13)
    e('li', 4, 64)
    e('li', 5, 7)
    e('and', 2, 4)
    e('lbu', 4, 3, 14)
    e('and', 4, 5)
    e('or', 2, 4)
    if not patched:
        e('li', 4, 255)
        e('and', 2, 4)
    e('beqz', 2, 'reset')
    e('lbu', 2, 3, 23)
    e('li', 3, 4)
    e('and', 2, 3)
    if not patched: e('and', 2, 4)
    e('beqz', 2, values['exit'])
    p.label('reset')
    e('lui', 2, values['reset_upper'])
    if not patched: e('move', 4, 2)
    e('li', 3, 0)
    if patched:
        e('sb', 3, 2, values['reset_first'])
        e('sb', 3, 2, values['reset_second'])
    else:
        e('addiu', 2, 2, values['reset_second'])
        e('sb', 3, 4, values['reset_first'])
        e('sb', 3, 2, 0)
    e('lui', 2, values['flag_upper'])
    e('li', 3, 1)
    if not patched: e('addiu', 4, 4, values['reset_first'])
    e('sb', 3, 2, values['flag_offset'])
    e('b', values['exit'])
    return p.finish()


def policy(start, upper, offset, veto):
    p = Program(start)
    e = p.emit
    e('addiu', 29, 29, -24)
    e('sw', 31, 29, 20)
    e('sw', 16, 29, 16)
    e('lui', 2, upper)
    e('lbu', 16, 2, offset)
    e('li', 2, 1)
    e('srl', 16, 16, 1)
    e('and', 16, 2)
    e('jal', veto)
    e('beqz', 2, 'return')
    e('li', 16, 0)
    p.label('return')
    e('move', 2, 16)
    e('lw', 7, 29, 20)
    e('lw', 16, 29, 16)
    e('addiu', 29, 29, 24)
    e('jr', 7)
    return p.finish()


def crc_algorithm(start):
    p = Program(start)
    e = p.emit
    e('move', 2, 6)
    p.label('length')
    e('li', 3, 65535)
    e('addiu', 4, 4, -1)
    e('and', 4, 3)
    e('cmp', 4, 3)
    e('btnez', 'byte')
    e('jr', 31)
    p.label('byte')
    e('lbu', 3, 5, 0)
    e('xor', 2, 3)
    e('li', 3, 8)
    p.label('bit')
    e('srl', 6, 2, 7)
    e('sll', 2, 2, 1)
    e('beqz', 6, 'mask')
    e('li', 6, 7)
    e('xor', 2, 6)
    e('sll', 2, 2, 24)
    e('sra', 2, 2, 24)
    p.label('mask')
    e('li', 6, 255)
    e('addiu', 3, 3, -1)
    e('and', 2, 6)
    e('bnez', 3, 'bit')
    e('addiu', 5, 5, 1)
    e('b', 'length')
    return p.finish()


def crc_compare(start):
    p = Program(start)
    e = p.emit
    e('lui', 2, 0xa010)
    e('addiu', 2, 2, 424)
    e('lbu', 3, 2, 5)
    e('lbu', 2, 2, 6)
    e('xor', 2, 3)
    e('sltiu', 2, 1)
    e('move', 2, 24)
    e('jr', 31)
    return p.finish()


def crc_receiver(start, crc, copier, writer, size):
    """Recognize the complete known receiver, including the partial last chunk."""
    if size & 65535: raise ValueError('receiver expects a whole number of banks')
    p = Program(start)
    e = p.emit
    e('addiu', 29, 29, -32)
    e('sw', 31, 29, 28)
    e('sw', 17, 29, 24)
    e('sw', 16, 29, 20)
    e('lui', 16, 0xa010)
    e('addiu', 16, 16, 424)
    e('lhu', 2, 16, 8)
    e('sltu', 2, 5)
    e('li', 2, 0)
    e('btnez', 'return')
    e('move', 17, 5)
    e('bnez', 6, 'chunk')
    e('move', 6, 5)
    e('move', 5, 4)
    e('lui', 4, 0xa010)
    e('addiu', 4, 4, 5120)
    e('jal', copier)
    p.label('chunk')
    e('lhu', 3, 16, 8)
    e('lui', 5, size >> 16)
    e('lw', 2, 16, 20)
    e('divu', 5, 3)
    e('lw', 4, 16, 24)
    e('addu', 4, 2, 4)
    e('lw', 2, 16, 12)
    e('addu', 2, 5, 2)
    e('mfhi', 6)
    e('bnez', 6, 'partial')
    e('subu', 2, 2, 3)
    e('xor', 2, 4)
    e('bnez', 2, 'accumulate')
    e('lui', 2, 0xa010)
    e('addu', 3, 3, 2)
    e('lbu', 2, 3, 5119)
    e('addiu', 3, 3, 5119)
    e('sb', 2, 16, 5)
    e('li', 2, 1)
    e('neg', 2)
    e('sb', 2, 3, 0)
    p.label('accumulate')
    e('lbu', 6, 16, 6)
    e('lui', 5, 0xa010)
    e('addiu', 5, 5, 5120)
    e('move', 4, 17)
    e('jal', crc)
    e('sb', 2, 16, 6)
    e('lw', 3, 16, 20)
    e('lw', 2, 16, 16)
    e('sltu', 3, 2)
    e('li', 2, 1)
    e('bteqz', 'return')
    e('move', 4, 17)
    e('jal', writer)
    p.label('return')
    e('lw', 7, 29, 28)
    e('lw', 17, 29, 24)
    e('lw', 16, 29, 20)
    e('addiu', 29, 29, 32)
    e('jr', 7)
    p.label('partial')
    e('div', 5, 3)
    e('mfhi', 3)
    e('subu', 2, 2, 3)
    e('xor', 2, 4)
    e('bnez', 2, 'accumulate')
    e('lui', 2, 0xa010)
    e('addu', 2, 3, 2)
    e('addiu', 2, 2, 5119)
    e('move', 17, 3)
    e('lbu', 3, 2, 0)
    e('sb', 3, 16, 5)
    e('li', 3, 1)
    e('neg', 3)
    e('sb', 3, 2, 0)
    e('b', 'accumulate')
    return p.finish()
